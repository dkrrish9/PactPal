"""
Data Models for AI Price Negotiator & Scope Change Requests
Linked Task: C38 / A12 (Milestone 3: Money & Extras)
"""

from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import List, Optional, Dict, Any
from datetime import datetime, timezone
import uuid

class ComplexityLevel(str, Enum):
    """Estimated technical complexity of the requested scope change."""
    TRIVIAL = "TRIVIAL"  # Text tweak, minor color/CSS change (< 4 hours)
    LOW = "LOW"          # New static UI component, simple form validation (4-12 hours)
    MEDIUM = "MEDIUM"    # Third-party OAuth, REST API endpoint, database schema update (12-36 hours)
    HIGH = "HIGH"        # Payment gateway, multi-role auth, complex state management (36-72 hours)
    EXTREME = "EXTREME"  # Full subsystem architecture, custom algorithms (> 72 hours)

@dataclass
class ChangeRequestProposal:
    """
    Structured proposal generated by the AI Price Negotiator evaluating
    a requested scope change against the original contract.
    """
    contract_id: str
    description: str
    proposed_price: float  # Recommended extra funding in contract currency
    proposed_extra_time_hours: int  # Recommended deadline extension in hours
    ai_reasoning: str  # Plain-language market rationale and scope breakdown
    complexity: ComplexityLevel = ComplexityLevel.MEDIUM
    suggested_feature_title: str = ""
    suggested_acceptance_test: str = ""
    suggested_weight_percent: float = 0.0
    proposed_by_id: Optional[str] = None
    change_request_id: str = field(default_factory=lambda: f"CR-{uuid.uuid4().hex[:8].upper()}")
    status: str = "PROPOSED"  # PROPOSED | ACCEPTED | REJECTED | COUNTERED
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["complexity"] = self.complexity.value
        return data


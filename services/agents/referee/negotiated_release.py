"""
Negotiated Partial Release Engine ('Fix it or accept 80% now')
Linked Tasks: C47 / A14 (Milestone 3: Money & Extras)

Generates agentic compromise settlement offers when a deliverable has minor flaws.
Stores seller choices (Accept payout vs Fix & resubmit) and triggers
either settlement payout or container re-verification.
"""

from enum import Enum
from dataclasses import dataclass, field, asdict
from typing import List, Optional, Dict, Any, Union
from datetime import datetime, timezone, timedelta
import uuid

from .models import RefereeDecision, DecisionOutcome

class SellerChoice(str, Enum):
    """Available choices presented to the seller upon partial verification."""
    ACCEPT_PARTIAL_PAYOUT = "ACCEPT_PARTIAL_PAYOUT"  # Accept passed amount now, close milestone
    FIX_AND_RESUBMIT = "FIX_AND_RESUBMIT"            # Request 24-48h extension to fix flaws & re-verify
    DISPUTE = "DISPUTE"                              # Dispute referee decision in formal room

@dataclass
class SettlementOffer:
    """
    Agentic compromise settlement offer generated by the AI Referee.
    Gives the seller the choice to take proportional payout immediately or fix flaws.
    """
    contract_id: str
    decision_id: str
    total_amount: float
    currency: str
    passed_amount: float
    refund_amount: float
    passed_weight: float
    failed_weight: float
    failed_features: List[Dict[str, Any]]
    fix_window_hours: int = 48
    conversational_offer: str = ""
    offer_id: str = field(default_factory=lambda: f"OFFER-{uuid.uuid4().hex[:8].upper()}")
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

@dataclass
class ChoiceResolution:
    """
    Audit record of the seller's decision.
    Triggers either final financial settlement (SETTLED) or container re-verification (IN_PROGRESS).
    """
    resolution_id: str
    offer_id: str
    contract_id: str
    seller_id: str
    choice: SellerChoice
    previous_state: str = "DECISION"
    next_state: str = "SETTLED"  # SETTLED | IN_PROGRESS | DISPUTE
    payout_instruction: Optional[Dict[str, Any]] = None
    reverification_schedule: Optional[Dict[str, Any]] = None
    note: str = ""
    audit_log_entry: str = ""
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["choice"] = self.choice.value
        return data

class NegotiatedReleaseEngine:
    """
    Referee settlement engine managing partial release compromises,
    seller decision logging, and downstream action dispatching.
    """

    def generate_offer(
        self,
        decision: RefereeDecision,
        contract: Union[Dict[str, Any], Any],
        fix_window_hours: int = 48
    ) -> SettlementOffer:
        """
        Synthesizes a compromise settlement offer for a partially passed deliverable.
        """
        c_dict = self._normalize(contract)
        contract_id = decision.contract_id or c_dict.get("id", "contract_unknown")
        currency = decision.currency or c_dict.get("currency", "USD")
        total_amount = decision.total_amount or float(c_dict.get("total_amount", 0.0))

        failed_features = [
            f.to_dict() if hasattr(f, "to_dict") else f
            for f in decision.feature_decisions
            if getattr(f, "status", "") == "FAILED" or (isinstance(f, dict) and f.get("status") == "FAILED")
        ]

        # Generate conversational compromise message
        failed_names = ", ".join(
            f.get("feature_title") if isinstance(f, dict) else getattr(f, "feature_title", "Deliverable")
            for f in failed_features
        ) or "unpassed acceptance tests"

        conversational_offer = (
            f"### 🤝 AI Referee Compromise Offer: Fix It or Accept {decision.passed_weight:.0f}% Now\n\n"
            f"Your deliverable passed **{decision.passed_weight:.1f}%** of acceptance criteria "
            f"(`{currency} {decision.passed_amount:,.2f}`).\n"
            f"However, the following deliverable(s) did not pass verification: **{failed_names}**.\n\n"
            f"You have two options:\n"
            f"1. **Option A (Accept Partial Payout)**: Receive `{currency} {decision.passed_amount:,.2f}` immediately. "
            f"The remaining `{currency} {decision.refund_amount:,.2f}` will be refunded to the buyer and the milestone will settle.\n"
            f"2. **Option B (Fix and Resubmit)**: Receive an extra **{fix_window_hours} hours** to fix the issue and push a new commit "
            f"for container re-verification to earn the full 100% `{currency} {total_amount:,.2f}` payout."
        )

        return SettlementOffer(
            contract_id=contract_id,
            decision_id=decision.decision_id,
            total_amount=total_amount,
            currency=currency,
            passed_amount=decision.passed_amount,
            refund_amount=decision.refund_amount,
            passed_weight=decision.passed_weight,
            failed_weight=decision.failed_weight,
            failed_features=failed_features,
            fix_window_hours=fix_window_hours,
            conversational_offer=conversational_offer
        )

    def process_seller_choice(
        self,
        offer: SettlementOffer,
        choice: Union[SellerChoice, str],
        seller_id: str,
        contract: Union[Dict[str, Any], Any],
        note: str = ""
    ) -> ChoiceResolution:
        """
        Stores the seller's choice and produces the downstream payout or re-verification triggers.
        """
        c_dict = self._normalize(contract)
        contract_seller_id = c_dict.get("seller_id")
        if contract_seller_id and seller_id != contract_seller_id and seller_id not in ("ADMIN", "PRICE_NEGOTIATOR"):
            raise PermissionError(f"User '{seller_id}' is not the assigned seller for contract '{offer.contract_id}'.")

        choice_enum = SellerChoice(choice) if isinstance(choice, str) else choice
        res_id = f"RES-{uuid.uuid4().hex[:8].upper()}"

        # -------------------------------------------------------------
        # CHOICE 1: ACCEPT_PARTIAL_PAYOUT ➔ DECISION to SETTLED
        # -------------------------------------------------------------
        if choice_enum == SellerChoice.ACCEPT_PARTIAL_PAYOUT:
            next_state = "SETTLED"
            payout_instruction = {
                "action": "CAPTURE_AND_DISBURSE",
                "contract_id": offer.contract_id,
                "seller_id": seller_id,
                "passed_amount": offer.passed_amount,
                "refund_amount": offer.refund_amount,
                "currency": offer.currency,
                "reason": f"Seller accepted {offer.passed_weight:.1f}% partial settlement offer."
            }
            reverification = None
            audit_log = (
                f"[REFEREE RESOLUTION] Seller '{seller_id}' accepted partial release of {offer.currency} "
                f"{offer.passed_amount:,.2f} ({offer.passed_weight:.1f}%). "
                f"Escrow settlement executed: {offer.currency} {offer.refund_amount:,.2f} refunded to buyer. State: SETTLED."
            )

        # -------------------------------------------------------------
        # CHOICE 2: FIX_AND_RESUBMIT ➔ DECISION to IN_PROGRESS
        # -------------------------------------------------------------
        elif choice_enum == SellerChoice.FIX_AND_RESUBMIT:
            next_state = "IN_PROGRESS"
            payout_instruction = None

            # Calculate revision cutoff
            now = datetime.now(timezone.utc)
            new_cutoff = now + timedelta(hours=offer.fix_window_hours)
            new_deadline_iso = new_cutoff.isoformat()

            reverification = {
                "action": "REVERIFY_SANDBOX",
                "contract_id": offer.contract_id,
                "seller_id": seller_id,
                "fix_window_hours": offer.fix_window_hours,
                "extended_deadline": new_deadline_iso,
                "failed_features_to_fix": [f.get("feature_id") or f.get("id") for f in offer.failed_features],
                "next_submission_attempt": 2
            }
            audit_log = (
                f"[REFEREE RESOLUTION] Seller '{seller_id}' chose to fix and resubmit. "
                f"Granted +{offer.fix_window_hours}h extension until {new_deadline_iso}. "
                f"Contract transitioned from DECISION to IN_PROGRESS for re-verification."
            )

        # -------------------------------------------------------------
        # CHOICE 3: DISPUTE ➔ DECISION to DISPUTE
        # -------------------------------------------------------------
        else:
            next_state = "DISPUTE"
            payout_instruction = None
            reverification = None
            audit_log = (
                f"[REFEREE RESOLUTION] Seller '{seller_id}' disputed the referee evaluation. "
                f"Contract transitioned from DECISION to DISPUTE. Funds remain frozen in escrow."
            )

        return ChoiceResolution(
            resolution_id=res_id,
            offer_id=offer.offer_id,
            contract_id=offer.contract_id,
            seller_id=seller_id,
            choice=choice_enum,
            previous_state="DECISION",
            next_state=next_state,
            payout_instruction=payout_instruction,
            reverification_schedule=reverification,
            note=note,
            audit_log_entry=audit_log
        )

    def _normalize(self, contract: Any) -> Dict[str, Any]:
        if isinstance(contract, dict):
            return contract
        if hasattr(contract, "__dict__"):
            return contract.__dict__
        return {}

